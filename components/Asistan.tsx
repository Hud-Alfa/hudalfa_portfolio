'use client';

import { useCallback, useEffect, useRef, useState } from 'react';
import { createPortal } from 'react-dom';
import type { L, Lang } from '@/content/types';
import { site } from '@/content/site';
import { t } from '@/content/dictionary';
import { kilitle, kilitAc } from '@/lib/kilit';

type Kaynak = { id: string; ad: string; slug: string | null };
type Balon = { rol: 'user' | 'assistant'; metin: string; kaynaklar?: Kaynak[] };

const MAKS_MESAJ = 12;
const MAKS_UZUNLUK = 600;

const M = {
  ac: { tr: 'Asistana sor', en: 'Ask the assistant' },
  sorular: { tr: 'Sorular', en: 'Questions' },
  ad: { tr: 'Yasir’in asistanı', en: 'Yasir’s assistant' },
  alt: { tr: 'CV ve projelerden yanıtlar', en: 'Answers from the CV and projects' },
  karsilama: {
    tr: 'Merhaba! Yasir’in projeleri, deneyimi, eğitimi ya da yetkinlikleri hakkında sorabilirsin. Cevaplarım sitedeki içerikten geliyor.',
    en: 'Hi! You can ask about Yasir’s projects, experience, education or skills. My answers come from the content on this site.',
  },
  yer: { tr: 'Bir soru yaz…', en: 'Type a question…' },
  gonder: { tr: 'Gönder', en: 'Send' },
  yeni: { tr: 'Yeni sohbet', en: 'New chat' },
  kapat: { tr: 'Kapat', en: 'Close' },
  kaynaklar: { tr: 'Kaynaklar', en: 'Sources' },
  not: {
    tr: 'Yanıtlar yapay zeka ile üretilir ve hata içerebilir.',
    en: 'Answers are generated by AI and may contain mistakes.',
  },
  sinir: {
    tr: 'Biraz hızlı gittik. Birkaç dakika sonra tekrar dener misin?',
    en: 'That was a lot at once. Could you try again in a few minutes?',
  },
  kapali: { tr: 'Asistan şu anda kapalı.', en: 'The assistant is unavailable right now.' },
  genel: { tr: 'Bir şeyler ters gitti, tekrar dener misin?', en: 'Something went wrong, could you try again?' },
  uzun: { tr: `Soru en fazla ${MAKS_UZUNLUK} karakter olabilir.`, en: `Questions can be up to ${MAKS_UZUNLUK} characters.` },
  doldu: {
    tr: 'Bu sohbet doldu. Yeni bir sohbet başlatabilirsin.',
    en: 'This chat is full. You can start a new one.',
  },
} satisfies Record<string, L>;

const KONULAR: { ikon: keyof typeof IKON; baslik: L; soru: L }[] = [
  { ikon: 'klasor', baslik: { tr: 'Projeler', en: 'Projects' }, soru: { tr: 'Hangi projeleri geliştirdi?', en: 'Which projects has he built?' } },
  { ikon: 'kup', baslik: { tr: 'StarCAD', en: 'StarCAD' }, soru: { tr: 'StarCAD nedir, hangi teknolojilerle yapıldı?', en: 'What is StarCAD and how was it built?' } },
  { ikon: 'kep', baslik: { tr: 'Eğitim', en: 'Education' }, soru: { tr: 'Nerede okudu?', en: 'Where did he study?' } },
  { ikon: 'canta', baslik: { tr: 'Deneyim', en: 'Experience' }, soru: { tr: 'Hangi stajları yaptı?', en: 'Which internships has he done?' } },
  { ikon: 'kalkan', baslik: { tr: 'Siber güvenlik', en: 'Security' }, soru: { tr: 'Siber güvenlikte neler yapıyor?', en: 'What does he do in security?' } },
  { ikon: 'zarf', baslik: { tr: 'İletişim', en: 'Contact' }, soru: { tr: 'Nasıl iletişime geçebilirim?', en: 'How can I get in touch?' } },
];

const IKON = {
  klasor: 'M3 7a2 2 0 0 1 2-2h4l2 2h8a2 2 0 0 1 2 2v8a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2z',
  kup: 'M12 3 4 7.5v9L12 21l8-4.5v-9zM4 7.5 12 12l8-4.5M12 12v9',
  kep: 'M2 9 12 4l10 5-10 5zM6 11v5c3 2 9 2 12 0v-5',
  canta: 'M4 8h16v11H4zM9 8V5h6v3M4 13h16',
  kalkan: 'M12 3 5 6v5c0 4.5 3 8 7 10 4-2 7-5.5 7-10V6z',
  zarf: 'M3 6h18v12H3zM3 6l9 7 9-7',
  parilti: 'M12 3l1.8 5.2L19 10l-5.2 1.8L12 17l-1.8-5.2L5 10l5.2-1.8zM19 15l.8 2.2L22 18l-2.2.8L19 21l-.8-2.2L16 18l2.2-.8z',
  carpi: 'M6 6l12 12M18 6 6 18',
  yenile: 'M4 12a8 8 0 0 1 14-5.3M20 4v5h-5M20 12a8 8 0 0 1-14 5.3M4 20v-5h5',
} as const;

function Svg({ d, boyut = 18 }: { d: string; boyut?: number }) {
  return (
    <svg width={boyut} height={boyut} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.7" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
      <path d={d} />
    </svg>
  );
}

/** Model düz metin yazıyor; "•" ile başlayan satırlar liste olarak gösteriliyor. */
function Metin({ metin }: { metin: string }) {
  const satirlar = metin.split('\n').filter((s) => s.trim());
  return (
    <>
      {satirlar.map((s, i) =>
        s.trim().startsWith('•') ? (
          <p key={i} className="ast-madde">{s.trim().slice(1).trim()}</p>
        ) : (
          <p key={i}>{s}</p>
        ),
      )}
    </>
  );
}

export default function Asistan({ lang }: { lang: Lang }) {
  const [acik, setAcik] = useState(false);
  const [balonlar, setBalonlar] = useState<Balon[]>([]);
  const [girdi, setGirdi] = useState('');
  const [bekliyor, setBekliyor] = useState(false);
  const [hata, setHata] = useState<string | null>(null);
  const akisRef = useRef<HTMLDivElement>(null);
  const girdiRef = useRef<HTMLInputElement>(null);
  const tetikRef = useRef<HTMLButtonElement>(null);

  const kapat = useCallback(() => {
    setAcik(false);
    tetikRef.current?.focus();
  }, []);

  useEffect(() => {
    if (!acik) return;
    kilitle();
    girdiRef.current?.focus();
    const tus = (e: KeyboardEvent) => {
      // Üstte bir proje penceresi varsa Esc önce onu kapatsın.
      if (e.key === 'Escape' && !document.querySelector('.mdl')) kapat();
    };
    window.addEventListener('keydown', tus);
    return () => {
      window.removeEventListener('keydown', tus);
      kilitAc();
    };
  }, [acik, kapat]);

  useEffect(() => {
    const el = akisRef.current;
    if (el) el.scrollTop = el.scrollHeight;
  }, [balonlar, bekliyor]);

  const gonder = useCallback(
    async (ham: string) => {
      const soru = ham.trim();
      if (!soru || bekliyor) return;
      if (soru.length > MAKS_UZUNLUK) {
        setHata(t(M.uzun, lang));
        return;
      }
      const gidecek: Balon[] = [...balonlar, { rol: 'user', metin: soru }];
      if (gidecek.length > MAKS_MESAJ) {
        setHata(t(M.doldu, lang));
        return;
      }
      setHata(null);
      setGirdi('');
      setBekliyor(true);
      setBalonlar([...gidecek, { rol: 'assistant', metin: '' }]);

      try {
        const res = await fetch('/api/asistan', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ lang, mesajlar: gidecek.map(({ rol, metin }) => ({ rol, metin })) }),
        });
        if (!res.ok || !res.body) {
          throw new Error(res.status === 429 ? 'sinir' : res.status === 503 ? 'kapali' : 'genel');
        }
        let kaynaklar: Kaynak[] = [];
        try {
          kaynaklar = JSON.parse(decodeURIComponent(res.headers.get('X-Kaynaklar') ?? '[]'));
        } catch {
          /* kaynaklar gösterilmez */
        }
        const okuyucu = res.body.getReader();
        const coz = new TextDecoder();
        let birikim = '';
        for (;;) {
          const { done, value } = await okuyucu.read();
          if (done) break;
          birikim += coz.decode(value, { stream: true });
          const anlik = birikim;
          setBalonlar((b) => [...b.slice(0, -1), { rol: 'assistant', metin: anlik }]);
        }
        setBalonlar((b) => [...b.slice(0, -1), { rol: 'assistant', metin: birikim, kaynaklar }]);
      } catch (e) {
        const tur = e instanceof Error ? e.message : 'genel';
        setHata(t(tur === 'sinir' ? M.sinir : tur === 'kapali' ? M.kapali : M.genel, lang));
        // Cevapsız kalan soru da geri alınıyor; ziyaretçi aynı soruyu yeniden gönderebilir.
        setBalonlar((b) => b.slice(0, -2));
        setGirdi(soru);
      } finally {
        setBekliyor(false);
      }
    },
    [balonlar, bekliyor, lang],
  );

  const kaynakAc = (k: Kaynak) => {
    if (k.slug) window.dispatchEvent(new CustomEvent('hudalfa:proje', { detail: k.slug }));
  };

  const sifirla = () => {
    setBalonlar([]);
    setHata(null);
    setGirdi('');
    girdiRef.current?.focus();
  };

  const sonAsistanBos = bekliyor && balonlar[balonlar.length - 1]?.metin === '';

  return (
    <>
      <button
        ref={tetikRef}
        type="button"
        className={`ast-tetik${acik ? ' gizli' : ''}`}
        onClick={() => setAcik(true)}
        aria-label={t(M.ac, lang)}
        aria-haspopup="dialog"
      >
        <Svg d={IKON.parilti} boyut={20} />
        <span className="ast-tetik-etiket">{t(M.ac, lang)}</span>
      </button>

      {acik
        ? createPortal(
            <div
              className="ast-katman"
              onClick={(e) => {
                if (e.target === e.currentTarget) kapat();
              }}
            >
              <div className="ast" role="dialog" aria-modal="true" aria-label={t(M.ad, lang)}>
                <aside className="ast-sol">
                  <h3>{t(M.sorular, lang)}</h3>
                  <div className="ast-konular">
                    {KONULAR.map((k) => (
                      <button key={k.baslik.tr} type="button" className="ast-konu" onClick={() => gonder(t(k.soru, lang))} disabled={bekliyor}>
                        <span className="ast-ikon">
                          <Svg d={IKON[k.ikon]} />
                        </span>
                        <span className="ast-konu-yazi">
                          <b>{t(k.baslik, lang)}</b>
                          <span>{t(k.soru, lang)}</span>
                        </span>
                      </button>
                    ))}
                  </div>
                  <button type="button" className="ast-yeni" onClick={sifirla} disabled={bekliyor || balonlar.length === 0}>
                    <Svg d={IKON.yenile} boyut={15} />
                    {t(M.yeni, lang)}
                  </button>
                </aside>

                <section className="ast-sag">
                  <header className="ast-ust">
                    {/* eslint-disable-next-line @next/next/no-img-element */}
                    <img src="/gorsel/profil-v2.jpg" alt="" className="ast-avatar" />
                    <div>
                      <b>{t(M.ad, lang)}</b>
                      <span>{t(M.alt, lang)}</span>
                    </div>
                  </header>

                  <div className="ast-akis" ref={akisRef} aria-live="polite">
                    <div className="balon asistan">
                      <p>{t(M.karsilama, lang)}</p>
                    </div>
                    {balonlar.map((b, i) =>
                      b.rol === 'assistant' && b.metin === '' ? null : (
                        <div key={i} className={`balon-sar ${b.rol === 'user' ? 'ben' : 'asistan'}`}>
                          <div className={`balon ${b.rol === 'user' ? 'ben' : 'asistan'}`}>
                            {b.rol === 'user' ? <p>{b.metin}</p> : <Metin metin={b.metin} />}
                          </div>
                          {b.kaynaklar && b.kaynaklar.length > 0 ? (
                            <div className="ast-kaynaklar" aria-label={t(M.kaynaklar, lang)}>
                              {b.kaynaklar.map((k) =>
                                k.slug ? (
                                  <button key={k.id} type="button" onClick={() => kaynakAc(k)}>
                                    {k.ad}
                                  </button>
                                ) : (
                                  <span key={k.id}>{k.ad}</span>
                                ),
                              )}
                            </div>
                          ) : null}
                        </div>
                      ),
                    )}
                    {sonAsistanBos ? (
                      <div className="balon asistan yaziyor" aria-label="…">
                        <i />
                        <i />
                        <i />
                      </div>
                    ) : null}
                    <p className="ast-not">{t(M.not, lang)}</p>
                  </div>

                  <div className="ast-mobil-konular">
                    {KONULAR.map((k) => (
                      <button key={k.baslik.tr} type="button" onClick={() => gonder(t(k.soru, lang))} disabled={bekliyor}>
                        {t(k.baslik, lang)}
                      </button>
                    ))}
                  </div>

                  {hata ? (
                    <p className="ast-hata" role="status">
                      {hata}{' '}
                      {hata === t(M.kapali, lang) || hata === t(M.genel, lang) ? (
                        <a href={`mailto:${site.email}`}>{site.email}</a>
                      ) : null}
                    </p>
                  ) : null}

                  <form
                    className="ast-alt"
                    onSubmit={(e) => {
                      e.preventDefault();
                      gonder(girdi);
                    }}
                  >
                    <input
                      ref={girdiRef}
                      value={girdi}
                      onChange={(e) => {
                        setGirdi(e.target.value);
                        if (hata) setHata(null);
                      }}
                      placeholder={t(M.yer, lang)}
                      maxLength={MAKS_UZUNLUK}
                      aria-label={t(M.yer, lang)}
                    />
                    <button type="submit" className="ast-gonder" disabled={bekliyor || !girdi.trim()}>
                      {t(M.gonder, lang)}
                    </button>
                  </form>
                </section>

                <div className="ast-dis">
                  <button type="button" onClick={kapat} aria-label={t(M.kapat, lang)}>
                    <Svg d={IKON.carpi} boyut={22} />
                  </button>
                  <button type="button" onClick={sifirla} aria-label={t(M.yeni, lang)} disabled={bekliyor || balonlar.length === 0}>
                    <Svg d={IKON.yenile} boyut={22} />
                  </button>
                </div>
              </div>
            </div>,
            document.body,
          )
        : null}
    </>
  );
}
